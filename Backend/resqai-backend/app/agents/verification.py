import logging
from typing import List, Tuple, Optional
from app.schemas.models import (
    IncidentRecord,
    TriageRecord,
    ResourceItem,
    PlanAction,
    VerificationData
)
from app.tools.resource_search import load_resources

logger = logging.getLogger("resqai.agents.verification")

def run_verification_agent(
    record: IncidentRecord,
    triage: TriageRecord,
    resources: List[ResourceItem],
    actions: List[PlanAction]
) -> Tuple[VerificationData, str, Optional[str]]:
    """
    Executes Agent 5 (Verification Agent).
    Validates the generated response, checks resource grounding, identifies unsupported claims,
    and enforces human-in-the-loop oversight.
    """
    flags: List[str] = []
    unsupported_claims: List[str] = []
    missing_evidence: List[str] = []
    contradictions: List[str] = []
    verified_ids: List[str] = []

    # 1. Ground truth check of all resources
    ground_truth = {r["resource_id"]: ResourceItem.model_validate(r) for r in load_resources()}
    # Matching annotations are generated by retrieval, not canonical dataset facts.
    annotations = {"match_reason", "evidence"}

    for res in resources:
        canonical = ground_truth.get(res.resource_id)
        if canonical is None:
            unsupported_claims.append(f"Resource {res.resource_id} is not present in predefined ground truth dataset")
        elif res.model_dump(exclude=annotations) != canonical.model_dump(exclude=annotations):
            unsupported_claims.append(f"Resource {res.resource_id} fields do not match the canonical synthetic dataset")
        else:
            verified_ids.append(res.resource_id)

    # Conflicting duplicates must not leave an ID marked as verified.
    invalid_ids = {
        res.resource_id for res in resources
        if res.resource_id not in ground_truth
        or res.model_dump(exclude=annotations) != ground_truth[res.resource_id].model_dump(exclude=annotations)
    }
    verified_ids = list(dict.fromkeys(rid for rid in verified_ids if rid not in invalid_ids))

    # Verify action plan resource references
    for act in actions:
        if act.assigned_resource_id:
            if act.assigned_resource_id not in ground_truth:
                unsupported_claims.append(
                    f"Action #{act.step} references non-existent resource ID '{act.assigned_resource_id}'"
                )
            if act.assigned_resource_id not in verified_ids:
                flags.append(
                    f"Action #{act.step} references resource '{act.assigned_resource_id}' which was not matched and verified"
                )

    # 2. Check for missing evidence or gaps
    if record.location == "Unknown / Unspecified" or len(record.location.split()) <= 1:
        missing_evidence.append("Report lacks a specific geographic street or coordinate location")
    flags.append("LOCATION_UNVERIFIED: Reported location has no independent geocoder or verification source; manual address verification is required")
    missing_evidence.append("Independent verification of reported location is unavailable")

    if record.affected_people is None:
        missing_evidence.append("Affected population count is unconfirmed in source report")

    # 3. Check for contradictions or alignment gaps
    if record.injuries_reported:
        has_medical_res = any(r.resource_id in verified_ids and r.resource_type in ["Hospital", "Mobile Medical"] for r in resources)
        if not has_medical_res:
            contradictions.append("Injuries were reported, but no medical facility or mobile clinic was retrieved")
            flags.append("MEDICAL_COVERAGE_GAP: Immediate medical resource allocation missing")

    if record.category.lower() == "flood":
        has_water_res = any(r.resource_id in verified_ids and r.resource_type in ["Water Rescue", "Shelter"] for r in resources)
        if not has_water_res:
            flags.append("SPECIALIZED_CAPABILITY_GAP: Flood incident lacking designated water rescue or shelter assets")

    if triage.priority == "Critical" and not record.injuries_reported and (record.affected_people or 0) <= 1:
        flags.append("PRIORITY_ELEVATION_NOTE: Critical priority assigned without recorded injuries or mass casualties")

    # 4. Mandatory Decision Support Safeguards
    # Always require human review before any real-world emergency dispatch action
    flags.append("DECISION_SUPPORT_SAFEGUARD: Automated dispatch disabled; human operator verification mandatory")

    verification_result = VerificationData(
        status="human_review_required",
        human_review_required=True,
        flags=flags,
        unsupported_claims=unsupported_claims,
        missing_evidence=missing_evidence,
        contradictions=contradictions,
        verified_resource_ids=verified_ids
    )

    logger.info(
        f"Verification completed: status='{verification_result.status}', "
        f"{len(flags)} flags, {len(unsupported_claims)} unsupported claims."
    )

    return verification_result, "rule-based-verification-auditor", None
